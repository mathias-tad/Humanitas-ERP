#!/usr/bin/env python3
"""Keep every AI-assistant rule file identical to AGENTS.md (the single source of truth).

Usage (from a repo root, or with --dir for the parent workspace folder):
  python scripts/sync_agent_rules.py            # write CLAUDE.md, .cursorrules (and GEMINI.md if present)
  python scripts/sync_agent_rules.py --check    # exit 1 if any copy differs (CI)
  python scripts/sync_agent_rules.py --dir ..   # also sync the workspace folder that holds both repos

Edit rules ONLY in AGENTS.md, then run this script (AGENTS.md rule 25).
"""
import sys
from pathlib import Path

NOTE = ("<!-- GENERATED FROM AGENTS.md by scripts/sync_agent_rules.py. "
        "Do not edit this file: edit AGENTS.md and run the script. -->")
TARGETS = ["CLAUDE.md", ".cursorrules"]
OPTIONAL = ["GEMINI.md"]


def sync(folder: Path, check: bool) -> bool:
    src = folder / "AGENTS.md"
    body = src.read_bytes().decode("utf-8").lstrip("﻿")
    eol = "\r\n" if "\r\n" in body else "\n"
    expected = (NOTE + eol + eol + body).encode("utf-8")
    ok = True
    for name in TARGETS + [n for n in OPTIONAL if (folder / n).exists()]:
        target = folder / name
        current = target.read_bytes() if target.exists() else b""
        if current == expected:
            print(f"{target}: in sync")
        elif check:
            print(f"{target}: OUT OF SYNC with AGENTS.md - run: python scripts/sync_agent_rules.py")
            ok = False
        else:
            target.write_bytes(expected)
            print(f"{target}: updated from AGENTS.md")
    return ok


if __name__ == "__main__":
    args = sys.argv[1:]
    check = "--check" in args
    folders = [Path(".")]
    if "--dir" in args:
        folders.append(Path(args[args.index("--dir") + 1]))
    sys.exit(0 if all([sync(f, check) for f in folders]) else 1)
